"""Leakage-safe, deck-aware features for the Dragapult imitation ranker (v3).

The same module is imported by the offline corpus builder and the submitted
runtime.  It reads only the acting player's observation: hidden opponent
cards, the eventual reward, and future replay state never enter a feature.

What changed from v1, and why
-----------------------------

v1 described an attachment with the target's card id and its *total* energy
count.  Phantom Dive costs one Fire and one Psychic, so "attach Fire to a
Dragapult holding Psychic" and "attach Fire to a Dragapult holding Fire" were
the same row to the model.  On the ladder it made 0.95 duplicate-colour
attachments per game against the teachers' 0.03, completed a colour pair 1.05
times per game against 1.62, and evolved Dragapult onto an already-powered
body 0.19 times per game against 0.70.  The result was Phantom Dive first used
on own-turn 6.2 instead of 3.8, and in 60% of games instead of 96%.

That is a representation failure, not a preference failure, so v2 fixes it in
the features rather than in a hand-written override: typed Energy per body,
the route ETA before and after the candidate action, and whether the candidate
completes the pair.

The second addition is resolved card knowledge.  The observation carries only
``id/hp/maxHp/energies/tools``, so v1 could not express "this Phantom Dive
knocks the Active out", "these damage counters take two prizes", or "our
Active dies to their board next turn".  The generated tables below supply
prize value, weakness, printed HP and the attack-cost frontier, following the
Grimmsnarl v3+ design that fixed the same blindness for that deck.

Third, ``OptionType.ABILITY`` carries ``area``/``index``, not the
``inPlayArea``/``inPlayIndex`` pair used by ATTACH and EVOLVE.  v1 read the
wrong pair, so its Recon Directive and Adrena-Brain flags were constant zero.

v3 adds the missing symmetric half of the route representation: board width.
The v2 ladder run fixed typed Energy but built 1.58 Dragapult ex per game
against the exact-list teachers' 1.88.  The model now sees the second-best
route, bench development, visible/unseen line inventory, exact line inventory
when a deck-search view is open, and whether an option develops a body or only
resources the existing attacker.
"""

