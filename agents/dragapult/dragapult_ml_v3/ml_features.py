def _as_int(value: Any, default: int = -1) -> int:
    try:
        return int(value)
    except (TypeError, ValueError):
        return default


def _cards(owner: dict[str, Any], area: str) -> list[dict[str, Any]]:
    value = owner.get(area) or []
    return [card for card in value if isinstance(card, dict)]


def _players(current: dict[str, Any]) -> tuple[int, dict[str, Any], dict[str, Any]]:
    players = current.get("players") or [{}, {}]
    players = list(players) + [{}, {}]
    your = _as_int(current.get("yourIndex"), 0)
    your = your if your in (0, 1) else 0
    me = players[your] if isinstance(players[your], dict) else {}
    opp = players[1 - your] if isinstance(players[1 - your], dict) else {}
    return your, me, opp


def _in_play(owner: dict[str, Any]) -> list[dict[str, Any]]:
    return _cards(owner, "active") + _cards(owner, "bench")


def _energies(card: dict[str, Any] | None) -> list[int]:
    if not isinstance(card, dict):
        return []
    return [int(value) for value in (card.get("energies") or [])]


def _energy_count(card: dict[str, Any] | None) -> int:
    if not isinstance(card, dict):
        return 0
    energies = card.get("energies")
    if isinstance(energies, list):
        return len(energies)
    cards = card.get("energyCards")
    return len(cards) if isinstance(cards, list) else 0


def _energy_type_count(card: dict[str, Any] | None, energy_type: int) -> int:
    if not isinstance(card, dict):
        return 0
    return sum(int(value) == energy_type for value in (card.get("energies") or []))


def _stage(card: dict[str, Any] | None) -> int:
    if not isinstance(card, dict):
        return -1
    return LINE_STAGE.get(_as_int(card.get("id")), -1)


def _missing_colors(energies: list[int]) -> int:
    return sum(color not in energies for color in ROUTE_COLORS)


def _route_eta(card: dict[str, Any] | None, attached: int | None = None) -> int:
    """Actions still needed before this body can pay for Phantom Dive.

    Evolution steps plus missing colours.  99 for anything off the line, so a
    tree can split "on the route" from "not on the route" with one threshold.
    """
    stage = _stage(card)
    if stage < 0:
        return 99
    energies = _energies(card)
    if attached is not None:
        energies = energies + [int(attached)]
    return (2 - stage) + _missing_colors(energies)


def _phantom_ready(card: dict[str, Any] | None) -> bool:
    if not isinstance(card, dict) or _as_int(card.get("id")) != DRAGAPULT_EX:
        return False
    energies = _energies(card)
    return FIRE_ENERGY in energies and PSYCHIC_ENERGY in energies


def _damage(card: dict[str, Any] | None) -> int:
    if not isinstance(card, dict):
        return 0
    return max(0, _as_int(card.get("maxHp"), 0) - _as_int(card.get("hp"), 0))


def prize_value(card_id: int) -> int:
    """Prizes taken for knocking this body out."""
    if card_id in MEGA_EX_IDS:
        return 3
    if card_id in RULE_BOX_IDS:
        return 2
    return 1


def _stadium_id(current: dict[str, Any]) -> int:
    stadium = current.get("stadium") or []
    if not isinstance(stadium, list) or not stadium:
        return -1
    first = stadium[0]
    return _as_int(first.get("id")) if isinstance(first, dict) else -1


def phantom_damage_to(card: dict[str, Any], stadium_id: int) -> float:
    """Damage Phantom Dive's 200 actually deals to ``card`` in the Active spot.

    Dragapult ex is a Pokemon ex, so the three walls that prevent all damage
    from a Pokemon ex take zero, and Neutralization Zone zeroes our damage to
    non-Rule-Box bodies.  Nothing in the pool is Dragon-weak, so the only
    other adjustment is Resistance.
    """
    card_id = _as_int(card.get("id"))
    if card_id < 0:
        return 0.0
    if card_id in EX_DAMAGE_BLOCKER_IDS:
        return 0.0
    if stadium_id == NEUTRALIZATION_ZONE_ID and card_id not in RULE_BOX_IDS:
        return 0.0
    if POKEMON_WEAKNESS_IDS.get(card_id) == DRAGAPULT_TYPE:
        return PHANTOM_DIVE_DAMAGE * 2
    if POKEMON_RESISTANCE_IDS.get(card_id) == DRAGAPULT_TYPE:
        return max(0.0, PHANTOM_DIVE_DAMAGE - 30.0)
    return PHANTOM_DIVE_DAMAGE


def counters_to_ko(card: dict[str, Any]) -> int:
    """Damage counters needed to knock this body out, capped at 99.

    Phantom Dive places counters rather than dealing damage, so the ex-damage
    walls do not apply here; this is a plain HP division.
    """
    hp = float(card.get("hp", 0) or 0)
    if hp <= 0:
        return 99
    return int(math.ceil(hp / PHANTOM_DIVE_COUNTER_DAMAGE))


def best_printed_damage(card: dict[str, Any], energy: int | None = None) -> float:
    """Highest printed attack damage this body can pay for right now.

    Printed only: "for each" scaling and counter placement read low, so this
    is a floor on the real threat and exact for the flat attacks that decide
    most turns.
    """
    frontier = ATTACK_COST_DAMAGE.get(_as_int(card.get("id")))
    if not frontier:
        return 0.0
    budget = _energy_count(card) if energy is None else int(energy)
    return float(max((d for c, d in frontier if c <= budget), default=0.0))


def damage_against(
    attacker: dict[str, Any],
    defender: dict[str, Any],
    energy: int | None = None,
) -> float:
    """``attacker``'s best printed damage after the defender's Weakness."""
    base = best_printed_damage(attacker, energy)
    if base <= 0.0:
        return 0.0
    attacker_type = POKEMON_TYPE_IDS.get(_as_int(attacker.get("id")), -1)
    defender_id = _as_int(defender.get("id"))
    if attacker_type < 0 or defender_id < 0:
        return base
    if POKEMON_WEAKNESS_IDS.get(defender_id) == attacker_type:
        return base * 2.0
    if POKEMON_RESISTANCE_IDS.get(defender_id) == attacker_type:
        return max(0.0, base - 30.0)
    return base


def incoming_damage(
    attackers: list[dict[str, Any]],
    defender: dict[str, Any],
    extra_energy: int = 1,
) -> float:
    """Most printed damage any of ``attackers`` can put on ``defender``.

    ``extra_energy`` defaults to one because the opponent attaches before they
    attack, so a body one Energy short is still a threat next turn.
    """
    best = 0.0
    for card in attackers:
        best = max(best, damage_against(
            card, defender, _energy_count(card) + extra_energy
        ))
    return best


def movable_counters(card: dict[str, Any]) -> int:
    """Damage counters Adrena-Brain can lift off this body, at most 3.

    The counters moved are also the damage the opponent takes, so a lightly
    damaged source both heals less and deals less.
    """
    damage = float(_damage(card))
    return int(min(MUNKIDORI_MOVE_COUNTERS, damage // 10))


def heals_needed(hp: float, threat: float) -> int:
    """Adrena-Brain moves needed to survive ``threat``; 0 if already safe."""
    if threat <= 0 or hp > threat:
        return 0
    deficit = threat - hp + 10.0
    return min(9, int(math.ceil(deficit / MUNKIDORI_MOVE_DAMAGE)))


def spread_prizes(bench: list[dict[str, Any]], counters: int) -> tuple[int, int]:
    """Best (prizes, bodies) the Phantom Dive spread can take off the Bench.

    Greedy by prizes-per-counter, which is optimal here because every counter
    is worth the same 10 damage and the bodies are independent.  Reported as a
    plan value: it says what the swing is worth before the placement context
    ever appears, which is what the decision to attack needs.
    """
    costs = sorted(
        (counters_to_ko(card), prize_value(_as_int(card.get("id"))))
        for card in bench
        if 0 < float(card.get("hp", 0) or 0)
    )
    budget = counters
    prizes = 0
    bodies = 0
    for cost, value in sorted(costs, key=lambda item: (item[0] / max(item[1], 1))):
        if cost <= budget:
            budget -= cost
            prizes += value
            bodies += 1
    return prizes, bodies


